async (page) => {
  const checks = [], errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const check=(name,condition)=>{if(!condition)throw new Error(name);checks.push({name,status:'passed'});};
  const owner='20000000-0000-0000-0000-000000000001';
  const base='http://127.0.0.1:57140';
  await page.goto(base);
  await page.getByRole('heading',{name:'Spreadsheet batches',exact:true}).waitFor();
  await page.getByLabel('Default location',{exact:true}).selectOption('40000000-0000-0000-0000-000000000001');
  const created=page.waitForResponse(r=>r.url()===`${base}/api/stock-intake-batches`&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Create batch',exact:true}).click();
  const batch=(await (await created).json()).batch;
  check('creates a server batch from the real review workspace',Boolean(batch.id));
  await page.getByLabel('Add CSV/XLSX originals',{exact:true}).setInputFiles('C:/TradeTrack/.m0-local/m2-browser/synthetic.xlsx');
  await page.getByRole('button',{name:'Select worksheets',exact:true}).click();
  const dialog=page.getByRole('dialog');
  for(const [index,name] of ['First','Second'].entries()){
    await dialog.getByRole('checkbox',{name:`Include ${name}`,exact:true}).check();
    const sheet=dialog.locator('fieldset').nth(index);
    for(const [label,column] of [['sku','0'],['quantity','1'],['receipt unit cost','2'],['purchase unit','3'],['conversion','4'],['supplier','5'],['invoice reference','6']])await sheet.getByLabel(label,{exact:true}).selectOption(column);
  }
  check('both worksheets have explicit complete-sheet mappings',await dialog.locator('fieldset').count()===2);
  await dialog.getByLabel('Repeated legitimate delivery reason (required for duplicates)',{exact:true}).fill('Repeated synthetic acceptance run');
  await dialog.getByRole('button',{name:'Save worksheet selection',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const accepted=page.waitForResponse(r=>r.url()===`${base}/api/stock-intake-batches/${batch.id}`&&r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Process configured sources',exact:true}).click();
  check('server accepts processing before the browser disconnects',(await accepted).ok());
  await page.goto('about:blank');
  let prepared;
  for(let attempt=0;attempt<120;attempt++){
    const response=await page.request.get(`${base}/api/stock-intake-batches/${batch.id}`,{headers:{'x-m0-actor':owner},timeout:10000});
    prepared=await response.json();
    if(prepared.sources?.[0]?.status==='prepared')break;
    if(prepared.sources?.[0]?.status==='failed')throw new Error(prepared.sources[0].error);
    await new Promise(resolve=>setTimeout(resolve,500));
  }
  check('preparation continues after the workspace is closed',prepared?.row_count===1200);
  check('two-sheet rows form one proposed supplier receipt',prepared.groups.length===1);
  await page.goto(base);
  await page.getByRole('heading',{name:'Resolve exceptions · 1,200 matching rows',exact:true}).waitFor();
  check('reconnection restores authoritative batch progress',await page.getByRole('button',{name:'Next rows',exact:true}).isEnabled());
  check('review paginates 100 actual rows',await page.getByRole('table').locator('tbody tr').count()===100);
  await page.getByRole('button',{name:'Next rows',exact:true}).click();
  await page.getByText('Page 2',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Inspect row',exact:true}).first().click();
  await page.getByRole('heading',{name:'Original extracted evidence',exact:true}).waitFor();
  check('row inspector shows source and review values side by side',await page.getByRole('heading',{name:'Reviewed values',exact:true}).isVisible());
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Select all included, unposted matching rows',exact:true}).click();
  await page.getByRole('button',{name:'Correct 1200 selected rows',exact:true}).click();
  await page.getByRole('checkbox',{name:'I explicitly checked every selected product, variant and purchase-unit conversion.',exact:true}).check();
  await page.getByRole('button',{name:'Apply selected correction',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check('explicit bulk correction covers selected rows across pages',true);
  await page.getByRole('button',{name:'Edit receipt group',exact:true}).click();
  await page.getByRole('dialog').getByLabel('duplicate reason',{exact:true}).fill('Repeated synthetic acceptance run');
  await page.getByRole('button',{name:'Save receipt group',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  await page.getByRole('button',{name:'Prepare all resolved receipts',exact:true}).click();
  await page.getByRole('button',{name:'Select all ready receipts',exact:true}).click();
  await page.getByRole('button',{name:'Approve 1 selected receipts',exact:true}).waitFor();
  check('approval requires the exclusions-summary acknowledgment',await page.getByRole('button',{name:'Approve 1 selected receipts',exact:true}).isDisabled());
  await page.getByRole('checkbox',{name:'I reviewed the selected receipts and summary, including failed, excluded and unselected work. Approve these reviewed deliveries once.',exact:true}).check();
  await page.getByRole('button',{name:'Approve 1 selected receipts',exact:true}).click();
  await page.getByText(/Saved receipt .*1200 lines posted together/).waitFor({timeout:60000});
  check('one batch approval reports the complete saved receipt',true);
  await page.setViewportSize({width:390,height:844});
  check('mobile layout contains horizontal tables without page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'build-evidence/m2/mobile-review.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'build-evidence/m2/desktop-review.png',fullPage:true});
  await page.getByRole('button',{name:'Switch to other shop',exact:true}).click();
  await page.getByRole('heading',{name:'Start a batch',exact:true}).waitFor();
  check('account switch removes prior batch rows and file names',await page.getByRole('heading',{name:/Resolve exceptions/}).count()===0);
  const foreign=await page.request.get(`${base}/api/stock-intake-batches/${batch.id}`,{headers:{'x-m0-actor':'20000000-0000-0000-0000-000000000066'}});
  check('another authorized shop cannot read the batch',foreign.status()===404);
  check('browser completed without uncaught component errors',errors.length===0);
  console.log(JSON.stringify({generatedAt:new Date().toISOString(),synthetic:true,hostedSessionAndStorageVerified:false,batchId:batch.id,checks},null,2));
}
