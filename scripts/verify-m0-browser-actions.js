/* eslint-disable @typescript-eslint/no-unused-expressions -- Playwright CLI consumes this function expression with --filename. */
async (page) => {
  const checks=[];
  const check=(name,condition)=>{if(!condition)throw new Error(name);checks.push({name,status:'passed'});};
  const ready=()=>page.getByText('Fixture ready. All records are synthetic.').waitFor({timeout:60000});
  const stock=async()=>Number(await(await page.request.get('http://127.0.0.1:57139/stock')).text());
  const reviews=()=>page.getByRole('button',{name:/^Review BROWSER-/});
  await page.reload();await ready();
  if(await reviews().count()===0)await page.getByRole('button',{name:'Save two offline checkouts',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('button[aria-label^="Review BROWSER-"]').length===2);
  const before=await stock();
  await page.reload();await ready();
  await page.waitForFunction(()=>document.querySelectorAll('button[aria-label^="Review BROWSER-"]').length===2);
  check('saved receipts survive page closure/reload',await reviews().count()===2);
  await page.setViewportSize({width:1280,height:900});
  check('desktop has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'build-evidence/m0/recovery-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Lose next acknowledgment',exact:true}).click();
  await reviews().first().click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('textbox',{name:'Reason for reconciliation'}).fill('Checked original synthetic receipt');
  await page.keyboard.press('Tab');
  check('review is keyboard operable',await page.evaluate(()=>document.activeElement?.textContent?.includes('Reconcile this saved receipt')));
  await page.keyboard.press('Enter');
  await dialog.getByRole('alert').filter({hasText:'Simulated acknowledgment loss'}).waitFor({timeout:60000});
  check('lost acknowledgment committed only one stock effect',await stock()===before-1);
  await dialog.getByRole('button',{name:'Reconcile this saved receipt',exact:true}).click();
  await dialog.waitFor({state:'hidden',timeout:60000});
  check('retry returns committed result without another decrement',await stock()===before-1);
  await reviews().first().click();
  await page.setViewportSize({width:375,height:812});
  await dialog.getByRole('textbox',{name:'Reason for reconciliation'}).fill('Checked second synthetic receipt');
  check('mobile review has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'build-evidence/m0/recovery-mobile.png',fullPage:true});
  await dialog.getByRole('button',{name:'Reconcile this saved receipt',exact:true}).click();
  await dialog.waitFor({state:'hidden',timeout:60000});
  check('both offline receipts reconcile through real PostgreSQL',await stock()===before-2);
  await page.getByRole('button',{name:'Save two offline checkouts',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('button[aria-label^="Review BROWSER-"]').length===2);
  await page.getByRole('button',{name:'Switch to other shop',exact:true}).click();
  await page.getByText('Current account: Other shop',{exact:true}).waitFor();
  check('other shop cannot see prior receipts',await reviews().count()===0);
  await page.getByRole('button',{name:'Return to test shop',exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll('button[aria-label^="Review BROWSER-"]').length===2);
  check('original account retains its queued receipts',await reviews().count()===2);
  for(let index=0;index<2;index++){
    await reviews().first().click();await dialog.getByRole('textbox',{name:'Reason for reconciliation'}).fill('Checked returning account receipt');
    await dialog.getByRole('button',{name:'Reconcile this saved receipt',exact:true}).click();await dialog.waitFor({state:'hidden',timeout:60000});
  }
  await page.getByRole('button',{name:'Save offline adjustment',exact:true}).click();
  await page.getByRole('button',{name:'Review adjustment',exact:true}).click();
  await dialog.getByRole('button',{name:'Retry saved adjustment',exact:true}).click();await dialog.waitFor({state:'hidden',timeout:60000});
  check('saved adjustment posts once after offline capture',await stock()===before-2);
  const rows='Name,Qty\n'+Array.from({length:20000},(_,index)=>`Synthetic ${index},1`).join('\n');
  await page.getByLabel('Choose a synthetic CSV or XLSX').setInputFiles({name:'synthetic-20000.csv',mimeType:'text/csv',buffer:Buffer.from(rows)});
  const status=page.getByRole('status').filter({hasText:/Prepared 20000 rows/});await status.waitFor({timeout:60000});
  const message=await status.textContent();
  check('worker prepares the complete 20000-row boundary',/Prepared 20000 rows/.test(message));
  check('worker parsing leaves a responsive UI heartbeat',Number(message.match(/heartbeat (\d+)/)?.[1])>0);
  await page.getByLabel('Choose a synthetic CSV or XLSX').setInputFiles({name:'synthetic-overflow.csv',mimeType:'text/csv',buffer:Buffer.from(rows+'\nOverflow,1')});
  await page.getByRole('status').filter({hasText:/exceeds 20,000/}).waitFor({timeout:60000});
  check('overflow is rejected explicitly without truncation',true);
  await page.getByLabel('Choose a synthetic CSV or XLSX').setInputFiles('.m0-local/browser/synthetic.xlsx');
  await page.getByRole('status').filter({hasText:/Prepared 2 rows/}).waitFor({timeout:60000});
  check('compressed XLSX remains supported in the browser worker',true);
  await page.emulateMedia({reducedMotion:'reduce'});
  check('reduced-motion preference remains available',await page.evaluate(()=>matchMedia('(prefers-reduced-motion: reduce)').matches));
  return {generatedAt:new Date().toISOString(),synthetic:true,hostedAuthVerified:false,beforeStock:before,afterStock:await stock(),worker:message,checks};
}
